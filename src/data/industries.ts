import type { Industry, IndustryImage } from "@/types/content";

/**
 * Industries Smart Channels serves — the sixteen approved by the client.
 *
 * Each `note` describes the *nature of the delivery environment*, not a
 * completed engagement. "Temporary networks stood up on tight timelines" is a
 * statement about what the sector demands; it is not a claim that a specific
 * project was delivered there. That distinction is deliberate — no project,
 * client or track record is implied anywhere in this file.
 *
 * ---------------------------------------------------------------------------
 * IMAGERY — photography is the intended primary source
 * ---------------------------------------------------------------------------
 * Each entry supports two images:
 *
 *   photo  — a real photograph of the environment. This is what the section is
 *            designed around and what should ship. Rendered whenever present.
 *   art    — a brand-generated abstract panel, used ONLY while `photo` is
 *            absent. It is a stopgap so the section is presentable before
 *            photography lands; it is not the intended final design.
 *
 * No industry photography has been supplied, so every entry currently falls
 * back to `art`. `industryPhotoReadiness()` reports the gap, the development
 * build labels each fallback panel, and the production checklist in
 * FINAL_PROJECT_REPORT.md treats this as an open item.
 *
 * TO ADD A PHOTOGRAPH
 *   1. Save it as `source-assets/industries/<id>.jpg` — the id below, exactly.
 *   2. Run `npm run assets:photos`. It produces an optimised WebP plus a blur
 *      placeholder and prints the `photo: { … }` block to paste in.
 *   3. Paste that block into the entry. Nothing else changes.
 *
 * `shotBrief` on each entry is the commissioning specification for that
 * photograph — hand it to a photographer or use it as stock search criteria.
 *
 * IMAGE REQUIREMENTS
 *   - 16:10 landscape, minimum 1600×1000, ideally 2400×1500
 *   - Composed with the lower third relatively clear: the industry title and
 *     note sit there over a scrim
 *   - Real environments, not obvious stock clichés (no handshakes, no
 *     lens-flare server rooms, no people pointing at screens)
 *   - Licensed for commercial web use, or owned outright
 */

/** Fallback art path for an industry, generated by scripts/generate-industry-art.mjs. */
function art(id: string): IndustryImage {
  return { src: `/images/industries/${id}.svg`, width: 1600, height: 1000 };
}

