/**
 * How many industries have real photography.
 *
 * The section is designed around photographs; the generated panels are a
 * stopgap. This is surfaced in the development build and in the launch
 * checklist so "still on fallback art" cannot quietly become permanent.
 */
export function industryPhotoReadiness(): {
  total: number;
  withPhoto: number;
  missing: readonly string[];
} {
  const missing = industries.filter((i) => !i.photo).map((i) => i.id);
  return {
    total: industries.length,
    withPhoto: industries.length - missing.length,
    missing,
  };
}
